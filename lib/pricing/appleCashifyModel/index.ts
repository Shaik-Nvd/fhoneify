import calibrationJson from './calibration.json';
import { evaluateAppleEvidence, roundTo10, type Calibration, type EvidenceOutcome, type ModelProfile } from './model';
import { findExact } from './exact';
import { SCOPE, evidenceModelKey, isAppleEvidenceModel, storageGbOf, type InferredPolicy } from './scope';
import type { DiagnosticsType } from '../../pricingCalculator';
import { InspectionRequiredError } from '../inspectionRequired';

/**
 * Entry point for the evidence-calibrated iPhone condition model.
 *
 * Scope is deliberate and narrow: a model/variant is priced here only when (1) it has a calibration profile fitted from
 * Cashify quotes of that exact model, (2) its storage variant is one of the variants the quotes were collected on,
 * and (3) scope.json enables it because its held-out validation met the acceptance thresholds. Everything else keeps
 * the existing engine, unchanged. scope.json is generated by scripts/pricing-evidence/validate-evidence-engine.ts.
 */
const CALIBRATION = calibrationJson as unknown as Calibration;

export const APPLE_EVIDENCE_VERSION = `apple-cashify-model/1+${CALIBRATION.version}+${SCOPE.version}`;
export { evidenceModelKey, isAppleEvidenceModel, storageGbOf };

/** The sibling's calibration with every value relabelled inferred: used only for a model without quotes of its own (scope.json fallbackFrom). */
function inferredFrom(source: ModelProfile, modelKey: string): ModelProfile {
  const p: ModelProfile = JSON.parse(JSON.stringify(source));
  const infer = (o: { support: string } | null | undefined) => { if (o) o.support = 'inferred'; };
  Object.values(p.classes).forEach(infer);
  Object.values(p.codes ?? {}).forEach(infer);
  if (p.age) Object.values(p.age).forEach(infer);
  infer(p.boxNo); infer(p.chargerNo); infer(p.cleanOffset);
  delete p.ageByStorage;
  delete p.functionalByStorage;
  p.observedInteractions = [];
  p.notes = [...p.notes, `no Cashify quotes of ${modelKey}: deductions borrowed from ${source.modelKey} (same generation), all inferred`];
  return { ...p, modelKey };
}
const profileFor = (modelKey: string): ModelProfile | null => {
  const own = CALIBRATION.models[modelKey];
  if (own) return own;
  const from = SCOPE.models[modelKey]?.fallbackFrom;
  return from && CALIBRATION.models[from] ? inferredFrom(CALIBRATION.models[from], modelKey) : null;
};

/**
 * True when this iPhone's calibrated rules carry a measured age effect (Cashify asks the age bracket after "warranty: Yes"). The crawled
 * questionnaire profile cannot see that conditional page and records the age question as NOT_ASKED, so for these models the customer's age
 * answer must reach the rules rather than be discarded.
 */
export function appleEvidenceAsksAge(model: string, storage: string | undefined | null): boolean {
  if (!isAppleEvidenceModel(model, storage)) return false;
  const profile = profileFor(evidenceModelKey(model));
  return Boolean(profile?.asks.age && profile.age);
}

export function appleEvidenceScope(model: string, storage: string | undefined | null): { profile: ModelProfile; storageGb: number } | null {
  if (!isAppleEvidenceModel(model, storage)) return null;
  const profile = profileFor(evidenceModelKey(model));
  const storageGb = storageGbOf(storage);
  return profile && storageGb != null ? { profile, storageGb } : null;
}

export interface AppleEvidenceQuote {
  outcome: Extract<EvidenceOutcome, { kind: 'PRICE' }>;
  modelKey: string;
  storageGb: number;
  inferredPolicy: InferredPolicy;
  /** 'exact': a recorded Cashify quote for this variant and these answers; 'model': computed by the calibrated rules. */
  source: 'exact' | 'model';
}

/**
 * Cashify-equivalent price for an iPhone, or null when the existing engine should price it (no recorded quote and no calibrated model).
 * Served quotes come from the calibrated rules alone: they depend on the current reference for every answer set. The recorded-quote index
 * (exact.json: one observed Cashify price per variant and answers, at the reference of its day) is an observation set, not a pricing source;
 * it is consulted only when a caller opts in with useRecordedQuotes (validation fixtures and tests), so it can never hide a wrong deduction.
 * Throws InspectionRequiredError only when Cashify itself declined the condition (recorded no-offer), the combination is
 * contradictory (cannot make calls plus other faults; more simultaneous faults than any Cashify quote shows) or the deductions leave nothing.
 */
export function appleEvidenceQuote(model: string, storage: string | undefined | null, reference: number, diagnostics: DiagnosticsType, options: { useRecordedQuotes?: boolean } = {}): AppleEvidenceQuote | null {
  const modelKey = evidenceModelKey(model);
  const gb = storageGbOf(storage);
  if (gb == null || !(reference > 0)) return null;
  const entry = SCOPE.models[modelKey];
  const calibrated = profileFor(modelKey);
  const profile = entry?.enabled ? calibrated : null;

  // the recorded quote is keyed with the calibrated profile (which fixes how age/warranty answers reduce to Cashify's state) whether or not the rules are enabled
  const hit = options.useRecordedQuotes ? findExact(modelKey, gb, calibrated, diagnostics, reference) : null;
  if (hit) {
    const [date, g0, recorded] = hit.entry;
    if (recorded == null) throw new InspectionRequiredError(`${modelKey}: Cashify declined exactly this condition (recorded no-offer${date ? `, ${date}` : ''})`);
    let price = recorded;
    const notes = [`recorded Cashify quote${date ? ` of ${date}` : ''} for this variant and these answers (Get Upto then ${g0})`];
    if (g0 !== reference) {
      // carry the recorded amount to today's reference by the model's own movement between the two references (proportionally without a model)
      const then = profile ? evaluateAppleEvidence(profile, g0, diagnostics, gb) : null;
      const now = profile ? evaluateAppleEvidence(profile, reference, diagnostics, gb) : null;
      price = then?.kind === 'PRICE' && now?.kind === 'PRICE' ? recorded + (now.price - then.price) : roundTo10(recorded * reference / g0);
      notes.push(`reference moved from ${g0} to ${reference}: recorded amount carried to the current reference`);
    }
    if (!(price > 0)) throw new InspectionRequiredError(`${modelKey}: recorded quote leaves nothing at the current reference`);
    return {
      outcome: { kind: 'PRICE', price, reference, breakdown: [{ rule: 'exact', label: `Recorded Cashify quote${date ? ` (${date})` : ''}`, amount: reference - price, support: 'measured' }], confidence: 'measured', floorApplied: false, state: 0, notes },
      modelKey, storageGb: gb, inferredPolicy: entry?.inferredPolicy ?? 'price', source: 'exact',
    };
  }

  if (!profile) return null;
  const outcome = evaluateAppleEvidence(profile, reference, diagnostics, gb);
  if (outcome.kind === 'UNSUPPORTED') return null; // an answer the model cannot read: leave it to the existing engine
  if (outcome.kind === 'NO_OFFER') throw new InspectionRequiredError(`${modelKey}: ${outcome.reason}`);
  const inferredPolicy = entry?.inferredPolicy ?? 'price';
  if (outcome.confidence === 'inferred') {
    if (inferredPolicy === 'legacy') return null;
    if (inferredPolicy === 'inspect') throw new InspectionRequiredError(`${modelKey}: ${outcome.notes[0] ?? 'condition not validated for this model'}`);
  }
  return { outcome, modelKey: profile.modelKey, storageGb: gb, inferredPolicy, source: 'model' };
}
